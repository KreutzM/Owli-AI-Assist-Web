import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import prettier from 'prettier';

const root = process.cwd();
const checkOnly = process.argv.includes('--check');
const excludedDirs = new Set([
  '.git',
  'node_modules',
  'dist',
  'coverage',
  'playwright-report',
  'test-results',
  'artifacts',
  'tmp',
]);
const excludedFiles = new Set([
  '.ai/file-tree.md',
  '.ai/repo-index.json',
  'pnpm-lock.yaml',
  'typecheck.log',
]);
const files = (await walk(root))
  .map((file) => slash(path.relative(root, file)))
  .filter((file) => !excludedFiles.has(file))
  .sort();

const records = await Promise.all(
  files.map(async (file) => {
    const info = await stat(path.join(root, file));
    return { path: file, bytes: info.size, area: file.split('/')[0] || 'root' };
  }),
);

const index = await prettier.format(
  JSON.stringify({
    schemaVersion: 1,
    generatedBy: 'tools/generate-repo-index.mjs',
    files: records,
  }),
  { parser: 'json' },
);

const grouped = Map.groupBy(records, (record) => record.area);
let treeSource = '# Generated Web Repository File Tree\n\n';
treeSource += 'Generated by `tools/generate-repo-index.mjs`. Do not edit manually.\n\n';
for (const [area, areaFiles] of [...grouped.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  treeSource += `## \`${area}/\`\n\n`;
  for (const file of areaFiles) treeSource += `- \`${file.path}\` (${file.bytes} B)\n`;
  treeSource += '\n';
}
const tree = await prettier.format(treeSource, { parser: 'markdown' });

await emit('.ai/repo-index.json', index);
await emit('.ai/file-tree.md', tree);
console.log(checkOnly ? 'AI repository index is current.' : 'AI repository index generated.');

async function emit(relative, content) {
  const target = path.join(root, relative);
  if (checkOnly) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== content) {
      const currentLines = current.split('\n');
      const expectedLines = content.split('\n');
      const firstDifferentLine = expectedLines.findIndex(
        (line, index) => line !== currentLines[index],
      );
      console.error(`${relative} is stale. Run pnpm ai:index.`);
      console.error(
        `First difference at line ${firstDifferentLine + 1}: current=${JSON.stringify(currentLines[firstDifferentLine])} expected=${JSON.stringify(expectedLines[firstDifferentLine])}`,
      );
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(target, content, 'utf8');
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    if (entry.isDirectory() && excludedDirs.has(entry.name)) continue;
    const resolved = path.join(directory, entry.name);
    if (entry.isDirectory()) result.push(...(await walk(resolved)));
    else result.push(resolved);
  }
  return result;
}

function slash(value) {
  return value.split(path.sep).join('/');
}
